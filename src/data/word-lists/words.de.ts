export function getWordsForDifficulty(difficulty: string, count: number): string[] {
  const words = wordsByDifficulty[difficulty] || wordsByDifficulty.easy
  const shuffled = [...words].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, count).map(w => w.word)
}
